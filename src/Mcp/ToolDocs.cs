using System.Collections.Generic;
using System.Linq;
using System.Text;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace TiaMcpServer.Mcp
{
    /// <summary>
    /// Renders the tool registry as documentation (`--dump-tools`). docs/TOOLS.md is
    /// generated from this, so the reference can never drift from the code.
    /// </summary>
    internal static class ToolDocs
    {
        private static readonly Dictionary<string, string> GroupTitles = new Dictionary<string, string>
        {
            ["core"] = "Core - connection, project, compile",
            ["plc"] = "PLC - blocks, data types, tags, watch tables",
            ["hmi"] = "HMI - WinCC Unified screens, tags, alarms",
            ["hardware"] = "Hardware - devices, modules, network",
            ["s7"] = "S7 - live values from the running PLC",
            ["diag"] = "Diagnostics - exploring the project and the Openness API"
        };

        public static string Json(ToolRegistry registry) =>
            new JArray(registry.All.Select(t =>
            {
                var o = t.ToMcp();
                o["group"] = t.Group;
                o["safety"] = t.Safety.ToString();
                return o;
            })).ToString(Formatting.Indented);

        private static string SafetyLabel(ToolDef t)
        {
            switch (t.Safety)
            {
                case Safety.ReadOnly: return "read-only";
                case Safety.Destructive: return "**destructive**";
                default: return t.CanBeDestructive ? "write / **destructive** when " + t.DestructiveWhenText : "write";
            }
        }

        public static string Markdown(ToolRegistry registry)
        {
            var sb = new StringBuilder();
            var all = registry.All;

            sb.AppendLine("# Tool reference");
            sb.AppendLine();
            sb.AppendLine("<!-- GENERATED by `TiaMcpServer.exe --dump-tools markdown`. Do not edit by hand. -->");
            sb.AppendLine();
            sb.AppendLine($"{all.Count} tools: " +
                          $"{all.Count(t => t.Safety == Safety.ReadOnly)} read-only, " +
                          $"{all.Count(t => t.Safety == Safety.Write && !t.CanBeDestructive)} write, " +
                          $"{all.Count(t => t.Safety == Safety.Write && t.CanBeDestructive)} write that can turn destructive, " +
                          $"{all.Count(t => t.Safety == Safety.Destructive)} always destructive.");
            sb.AppendLine();
            sb.AppendLine("| Safety class | Meaning | Available with |");
            sb.AppendLine("|---|---|---|");
            sb.AppendLine("| read-only | Never changes the project. May write an export file where you tell it to. | `--access readonly`, `write`, `full` |");
            sb.AppendLine("| write | Creates objects or changes properties. Nothing existing is removed. | `--access write`, `full` |");
            sb.AppendLine("| **destructive** | Deletes or replaces existing content, or discards unsaved work. Refused without `confirm: true`. | `--access full` |");
            sb.AppendLine();
            sb.AppendLine("See [SAFETY.md](SAFETY.md) for the full safety model.");
            sb.AppendLine();

            sb.AppendLine("## Overview");
            sb.AppendLine();
            foreach (var group in ServerOptions.AllGroups)
            {
                var tools = all.Where(t => t.Group == group).ToList();
                if (tools.Count == 0) continue;
                sb.AppendLine($"### {GroupTitles[group]} (`{group}`, {tools.Count})");
                sb.AppendLine();
                sb.AppendLine("| Tool | Safety | What it does |");
                sb.AppendLine("|---|---|---|");
                foreach (var t in tools)
                    sb.AppendLine($"| [`{t.Name}`](#{t.Name}) | {SafetyLabel(t)} | {t.Title} |");
                sb.AppendLine();
            }

            sb.AppendLine("## Details");
            sb.AppendLine();
            foreach (var group in ServerOptions.AllGroups)
            {
                foreach (var t in all.Where(t => t.Group == group))
                {
                    sb.AppendLine($"### {t.Name}");
                    sb.AppendLine();
                    sb.AppendLine($"*{t.Title}* - group `{t.Group}` - {SafetyLabel(t)}");
                    sb.AppendLine();
                    sb.AppendLine(t.Summary);
                    sb.AppendLine();

                    if (t.Properties.Count > 0)
                    {
                        sb.AppendLine("| Argument | Type | Required | Description |");
                        sb.AppendLine("|---|---|---|---|");
                        foreach (var p in t.Properties.Properties())
                        {
                            var schema = (JObject)p.Value;
                            var description = ((string)schema["description"] ?? "").Replace("|", "\\|").Replace("\n", " ");
                            sb.AppendLine($"| `{p.Name}` | {(string)schema["type"]} | {(t.Required.Contains(p.Name) ? "yes" : "")} | {description} |");
                        }
                        sb.AppendLine();
                    }
                }
            }

            return sb.ToString();
        }
    }
}
